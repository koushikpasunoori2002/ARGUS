"""
Evaluation summary for LogLlamalyzer.

Reads the structured final evaluation artifact generated by
final_evaluation.py instead of using hard-coded evaluation values.
"""

import json
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parents[3]

RESULTS_FILE = (
    PROJECT_ROOT
    / "outputs"
    / "results"
    / "final_evaluation_results.json"
)


def load_results():
    """Load the final evaluation results."""

    if not RESULTS_FILE.exists():
        raise FileNotFoundError(
            f"Final evaluation results not found: {RESULTS_FILE}"
        )

    with RESULTS_FILE.open(
        "r",
        encoding="utf-8",
    ) as file:
        return json.load(file)


def main():
    """Display the final evaluation summary."""

    results = load_results()

    print("=" * 60)
    print("LOGLLAMALYZER EVALUATION SUMMARY")
    print("=" * 60)

    print(
        f"\nProject: "
        f"{results['project']}"
    )

    print(
        f"Phase: "
        f"{results['evaluation']['phase']}"
    )

    print(
        f"Generated: "
        f"{results['evaluation']['generated_at_utc']}"
    )

    for name, evaluation in results["evaluations"].items():

        print(
            f"\n{name.replace('_', ' ').title()}"
        )

        print(
            f"Result: "
            f"{evaluation['passed']}/"
            f"{evaluation['total']}"
        )

        print(
            f"Rate: "
            f"{evaluation['rate_percent']:.1f}%"
        )

        print(
            f"Metric: "
            f"{evaluation['metric']}"
        )

        print(
            f"Interpretation: "
            f"{evaluation['interpretation']}"
        )

    performance = results["performance"]

    print("\nPerformance Measurements")

    print(
        "RAG full process: "
        f"{performance['rag_pipeline']['full_process_seconds']:.4f} s"
    )

    print(
        "Security analysis full process: "
        f"{performance['security_analysis']['full_process_seconds']:.4f} s"
    )

    print(
        "Security/RAG ratio: "
        f"{performance['comparison']['security_analysis_to_rag_ratio']:.4f}x"
    )

    print("\nLimitations")

    for limitation in results["limitations"]:
        print(f"- {limitation}")

    print("\n" + "=" * 60)
    print("EVALUATION SUMMARY COMPLETED")
    print("=" * 60)


if __name__ == "__main__":
    main()
